def area(a, h): 
    '''Принимает числа a, h - сторона и высота, опущенная к этой стороне, возвращает площадь треугольника с заданными параметрами'''
    return a * h / 2 

def perimeter(a, b, c): 
    '''Принимает числа a, b, c - стороны треугольника, возвращает периметр треугольника с заданными параметрами'''
    return a + b + c 
